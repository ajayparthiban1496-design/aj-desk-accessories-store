// Generates supabase/seed.sql from the same catalogue used in demo mode,
// so both modes always show identical products.
//   npm run seed:sql
import { createServer } from "vite";
import { writeFileSync } from "node:fs";

const server = await createServer({ server: { middlewareMode: true }, appType: "custom", logLevel: "error" });
const { seedProducts, seedReviews, categories } = await server.ssrLoadModule("/src/data/products.ts");
await server.close();

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

let sql = `-- Generated by scripts/generate-seed.mjs — do not edit by hand.\n-- Run after migrations: supabase db reset (local) or paste into the SQL editor.\n\nbegin;\n\n`;

sql += `insert into public.categories (slug, name, description, position) values\n`;
sql += categories.map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${i})`).join(",\n");
sql += `\non conflict (slug) do update set name = excluded.name, description = excluded.description;\n\n`;

for (const p of seedProducts) {
  sql += `with p as (\n  insert into public.products (slug, name, tagline, description, category_slug, price, compare_at_price, images, features, specs, badge, is_featured, is_active, created_at)\n`;
  sql += `  values (${q(p.slug)}, ${q(p.name)}, ${q(p.tagline)}, ${q(p.description)}, ${q(p.category)}, ${p.price}, ${p.compareAtPrice ?? "null"}, ${arr(p.images)}, ${arr(p.features)}, ${q(JSON.stringify(p.specs))}::jsonb, ${p.badge ? q(p.badge) : "null"}, ${p.isFeatured}, true, ${q(p.createdAt)})\n`;
  sql += `  on conflict (slug) do update set price = excluded.price\n  returning id\n)\n`;
  sql += `insert into public.product_variants (product_id, name, swatch, stock, position)\nselect p.id, v.name, v.swatch, v.stock, v.position from p, (values\n`;
  sql += p.variants.map((v, i) => `  (${q(v.name)}, ${q(v.swatch)}, ${v.stock}, ${i})`).join(",\n");
  sql += `\n) as v(name, swatch, stock, position)\non conflict (product_id, name) do nothing;\n\n`;

  for (const r of seedReviews.filter((r) => r.productId === p.id)) {
    sql += `insert into public.reviews (product_id, author_name, rating, title, body, created_at) select id, ${q(r.author)}, ${r.rating}, ${q(r.title)}, ${q(r.body)}, ${q(r.createdAt)} from public.products where slug = ${q(p.slug)};\n`;
  }
  // Restore the historical aggregate after the sample reviews were counted.
  sql += `update public.products set rating = ${p.rating}, review_count = ${p.reviewCount} where slug = ${q(p.slug)};\n\n`;
}

sql += `commit;\n\n-- Make yourself an admin after signing up:\n-- update public.profiles set role = 'admin' where id = (select id from auth.users where email = 'you@example.com');\n`;

writeFileSync("supabase/seed.sql", sql);
console.log(`Wrote supabase/seed.sql (${seedProducts.length} products, ${seedReviews.length} reviews)`);

// sitemap.xml — set SITE_URL to your production domain before running.
const site = (process.env.SITE_URL ?? "https://ajdesk.store").replace(/\/$/, "");
const paths = [
  "/", "/shop", "/about", "/contact", "/faq", "/shipping-returns", "/privacy", "/terms",
  ...categories.map((c) => `/shop?category=${c.slug}`),
  ...seedProducts.map((p) => `/products/${p.slug}`),
];
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${paths
  .map((p) => `  <url><loc>${site}${p.replace(/&/g, "&amp;")}</loc></url>`)
  .join("\n")}\n</urlset>\n`;
writeFileSync("public/sitemap.xml", xml);
console.log(`Wrote public/sitemap.xml (${paths.length} URLs)`);
